"""
D7: Citation as lookup.

Statute citations are never generated by the LLM. Each clause stores statute
codes in its metadata (clauses.statute_refs, e.g. "ICA_s74"); this module turns
those codes into citation text using a fixed registry.

- A code that is not in the registry is NOT guessed. It is reported as
  unresolved so a lawyer can add it, and no citation text is produced for it.
- D5 separately blocks the model from adding any new words (including statute
  names) to a clause, so citations can only enter a draft through here.

To add a statute: add one entry to STATUTES. Keep the code format
<ACT>_s<section>, matching what clause seed/verified files use.
"""

from __future__ import annotations

from pydantic import BaseModel, Field

ACTS = {
    "ICA": "Indian Contract Act, 1872",
    "MSMED": "Micro, Small and Medium Enterprises Development Act, 2006",
}

# code -> (act key, section). Sections listed are the ones referenced in the
# build plan and the Review Agent rules (s.27, s.28, s.74, MSMED s.15-16).
STATUTES: dict[str, tuple[str, str]] = {
    "ICA_s27": ("ICA", "27"),
    "ICA_s28": ("ICA", "28"),
    "ICA_s74": ("ICA", "74"),
    "MSMED_s15": ("MSMED", "15"),
    "MSMED_s16": ("MSMED", "16"),
}


class Citation(BaseModel):
    code: str
    text: str  # e.g. "Section 74, Indian Contract Act, 1872"


class CitationResult(BaseModel):
    citations: list[Citation] = Field(default_factory=list)
    unresolved: list[str] = Field(default_factory=list)


def format_citation(code: str) -> str | None:
    """Citation text for a code, or None if the code is unknown."""
    entry = STATUTES.get(code.strip()) if isinstance(code, str) else None
    if entry is None:
        return None
    act_key, section = entry
    return f"Section {section}, {ACTS[act_key]}"


def resolve_citations(codes: list[str]) -> CitationResult:
    """Resolve a clause's statute codes, de-duplicated, in their original order."""
    result = CitationResult()
    seen: set[str] = set()
    for code in codes or []:
        key = code.strip() if isinstance(code, str) else repr(code)
        if not key or key in seen:
            continue
        seen.add(key)
        text = format_citation(key)
        if text is None:
            result.unresolved.append(key)
        else:
            result.citations.append(Citation(code=key, text=text))
    return result
